#!/usr/bin/env python3
"""Build a match list for cricinfo_commentary.py from downloaded Cricsheet files.

Cricsheet names each match file by its Cricinfo match ID, so a folder of
Cricsheet JSON already lists every match in a competition. ESPN's commentary
feed accepts a league's constant series ID for any of its seasons, so no
season-by-season search of ESPN is needed.

Example (BBL, series 8044, since 2021):
    python matches_from_cricsheet.py --cricsheet-dir data/cricsheet/bbl --series-id 8044 \
        --since 2021-01-01 --out matches/bbl_2021_2026.txt

League series IDs: IPL 8048, BBL 8044, CPL 8623, SA20 21275, The Hundred (men's) 19601.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def main() -> int:
    parser = argparse.ArgumentParser(description="Match list from a folder of Cricsheet JSON files.")
    parser.add_argument("--cricsheet-dir", type=Path, required=True)
    parser.add_argument("--series-id", required=True, help="ESPN/Cricinfo league series ID")
    parser.add_argument("--since", default="2021-01-01", help="First match date, YYYY-MM-DD")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    matches = []
    for path in args.cricsheet_dir.glob("*.json"):
        if not path.stem.isdigit():
            continue
        info = json.loads(path.read_text(encoding="utf-8"))["info"]
        when = info["dates"][0]
        if when < args.since:
            continue
        event = info.get("event", {})
        number = event.get("match_number") or event.get("stage") or ""
        matches.append((when, int(path.stem), info, str(number)))
    matches.sort()

    season, lines = None, []
    for when, match_id, info, number in matches:
        if str(info.get("season")) != season:
            season = str(info.get("season"))
            lines.append(f"\n# {info.get('event', {}).get('name', '')} {season}")
        teams = " v ".join(info["teams"])
        outcome = info.get("outcome", {})
        result = outcome.get("winner", outcome.get("result", ""))
        lines.append(f"# {when} {teams}" + (f" (match {number})" if number else "") + (f": {result}" if result else ""))
        name = slug(f"{info['teams'][0]} vs {info['teams'][1]} {info.get('event', {}).get('name', '')} {season}")
        lines.append(f"https://www.espn.com/cricket/series/{args.series_id}/game/{match_id}/{name}")

    header = [f"# {len(matches)} matches from {args.cricsheet_dir} since {args.since}, series {args.series_id}",
              "# Generated by matches_from_cricsheet.py (Cricsheet file names are Cricinfo match IDs)"]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(matches)} matches to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
